#!/usr/bin/env bash
# Distribution: build dns-wizard.sh from this launcher and src/ with tools/build_bundle.py.
set -euo pipefail

case ${1-} in
    -h|--help)
        printf '%s\n' 'Usage: sudo bash dns-wizard.sh [--zones | --diagnose [--server IPv4] | --dry-run | --help]'
        exit 0
        ;;
esac

if ! command -v python3 >/dev/null 2>&1; then
    if [[ $# != 0 || ! -t 0 || $EUID != 0 ]]; then
        printf '%s\n' 'Python 3 is required. No packages were installed.' >&2
        exit 2
    fi
    if ! ( . /etc/os-release && [[ $ID = ubuntu && ( $VERSION_ID = 22.04 || $VERSION_ID = 24.04 ) ]] ); then
        printf '%s\n' 'Automatic dependency installation requires Ubuntu 22.04 or 24.04.' >&2
        exit 2
    fi
    apt_args=(--no-upgrade --no-install-recommends install python3)
    simulation=$(LC_ALL=C apt-get -s "${apt_args[@]}")
    printf '%s\n' "$simulation"
    if grep -Eq '^Remv |^Inst [^ ]+ \[' <<< "$simulation"; then
        printf '%s\n' 'Dependency simulation includes an upgrade or removal. Install Python manually.' >&2
        exit 2
    fi
    read -r -p 'Install Python 3 to open the UI? This is a package change [y/N] ' answer || exit 2
    [[ $answer = y || $answer = Y ]] || exit 2
    LC_ALL=C apt-get -y "${apt_args[@]}"
fi

# Keep the bundled modules in memory so the launcher can also run read-only.
exec python3 -IB -c '
import base64
import os
import runpy
import sys
import zipimport

if sys.version_info < (3, 10):
    sys.exit("DNS Wizard requires Python 3.10 or newer.")

sys.argv.pop(0)
try:
    with open(sys.argv[0], "rb") as launcher:
        _, start, payload = launcher.read().partition(b"\n: <<\x27DNS_WIZARD_BUNDLE\x27\n")
    encoded, end, tail = payload.partition(b"\nDNS_WIZARD_BUNDLE\n")
    if not start or not end or tail.strip():
        raise ValueError("embedded modules are missing or incomplete")
    archive = base64.b64decode(b"".join(encoded.split()), validate=True)
    fd = os.memfd_create("dns-wizard-modules", os.MFD_CLOEXEC)
    with os.fdopen(fd, "wb", closefd=False) as bundle:
        bundle.write(archive)
    location = f"/proc/self/fd/{fd}"
    zipimport.zipimporter(location).get_code("cli")
except (OSError, ValueError, zipimport.ZipImportError) as exc:
    print(f"Cannot load DNS Wizard from {sys.argv[0]}: {exc}", file=sys.stderr)
    sys.exit(2)

sys.path.insert(0, location)
try:
    runpy.run_module("cli", run_name="__main__")
finally:
    os.close(fd)
' "${BASH_SOURCE[0]}" "$@"

